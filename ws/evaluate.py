"""Benchmarks against naive baselines, on the synthetic world. Writes docs/evaluation.md.

    python -m ws.evaluate
"""
import random
import statistics

import numpy as np

from core import db

from . import forecast, rules, solver, world

H = world.HISTORY_DAYS


def people(loc):
    return [{**x, "id": x["n"]} for x in loc["workers"]]


def week_forecast(w, loc):
    f, _ = forecast.forecast(loc["tx"][:H], loc["promo"][:H], loc["rain"][:H], w["weekday"][:H], loc["promo"][H:], loc["rain"][H:], w["weekday"][H:])
    return f


def main():
    w = world.build()
    out = ["# Evaluation", "", "Generated by `python -m ws.evaluate` on the synthetic retailer (seed 9): 50 stores, 5,000 workers, two years of half-hourly demand.", ""]

    bt = [forecast.backtest(x["tx"][:H], x["promo"][:H], x["rain"][:H], w["weekday"][:H], 12) for x in w["locations"]]
    mean = lambda k: float(np.mean([b[k] for b in bt]))      # noqa: E731
    out += ["## 1. Demand forecast", "", "Rolling origin, the last 12 weeks, every store: each week forecast from everything before it. WAPE = total absolute error / total demand.", "",
            "| | Half-hour level | Daily totals |", "|---|---|---|",
            f"| Seasonal profile + promotion and rain effects (`{forecast.VERSION}`) | {mean('model_wape'):.1%} | {mean('model_daily_wape'):.1%} |",
            f"| Baseline: same weekday last week | {mean('baseline_wape'):.1%} | {mean('baseline_daily_wape'):.1%} |", "",
            f"The model is better in {sum(b['model_wape'] < b['baseline_wape'] for b in bt)} of {len(bt)} stores. Half-hour error is dominated by Poisson noise in the counts, which no forecast removes; "
            "the daily figure shows the part that can be learned.", ""]

    stores = sorted(w["locations"], key=lambda x: len(x["workers"]))[:6]
    rows, tot = [], {"g": [], "o": []}
    for loc in stores:
        ws = people(loc)
        dem = world.demand_dict(week_forecast(w, loc), loc["size"])
        g, o = solver.greedy(ws, dem), solver.optimize(ws, dem, time_limit=20)
        mg, mo = rules.metrics(ws, g["shifts"], dem), rules.metrics(ws, o["shifts"], dem)
        tot["g"].append(mg), tot["o"].append(mo)
        gap = (o["objective"] - o["bound"]) / o["objective"]
        rows.append(f"| {loc['name']} | {len(ws)} | ${mg['labor_cost']:,.0f} | ${mo['labor_cost']:,.0f} | {mo['labor_cost'] / mg['labor_cost'] - 1:+.1%} | {mg['fill_rate']:.1%} | {mo['fill_rate']:.1%} | {mg['preference_score']} | {mo['preference_score']} | "
                    f"{len(mg['hard_violations'])} / {len(mo['hard_violations'])} | {o['status'].lower()}, gap {gap:.2%} |")
    s = lambda k, m: sum(x[m] for x in tot[k])      # noqa: E731
    out += ["## 2. Schedule: constraint solver against first-fit", "", "The six smallest stores (so each week solves within the 20-second limit used in the demo), one week each, on forecast demand. "
            "Both methods obey the same rule pack; `rules.check` re-verifies every schedule independently of the solver.", "",
            "| Store | Workers | Cost, first-fit | Cost, solver | Change | Fill, first-fit | Fill, solver | Preference, first-fit | Preference, solver | Rule violations (ff / solver) | Solver status |", "|---|---|---|---|---|---|---|---|---|---|---|", *rows, "",
            f"Across the six: labor cost ${s('g', 'labor_cost'):,.0f} against ${s('o', 'labor_cost'):,.0f} ({s('o', 'labor_cost') / s('g', 'labor_cost') - 1:+.1%}); understaffed hours {s('g', 'understaffed_hours'):,.1f} against {s('o', 'understaffed_hours'):,.1f}; "
            f"overtime hours {s('g', 'overtime_hours'):.1f} against {s('o', 'overtime_hours'):.1f}; hours worked at times people asked to avoid {s('g', 'hours_in_avoided_times'):,.0f} against {s('o', 'hours_in_avoided_times'):,.0f}; "
            f"hours below contract {s('g', 'hours_below_contract'):,.0f} against {s('o', 'hours_below_contract'):,.0f}.", "",
            "The last figure goes the wrong way on purpose: the solver stops paying for hours nobody needs, and those hours were somebody's contracted hours. See the README's tradeoff section.", ""]

    loc = w["locations"][0]
    ws = people(loc)
    actual = world.demand_dict(loc["tx"][H:], loc["size"])
    plans = {"Model forecast": world.demand_dict(week_forecast(w, loc), loc["size"]), "Copy of last week": world.demand_dict(forecast.last_week(loc["tx"][:H], 7), loc["size"])}
    out += ["## 3. Does the better forecast matter? (demo store)", "", "The week is scheduled on each forecast, then scored against the demand that actually arrived (the simulator knows it).", "",
            "| Schedule built on | Labor cost | Understaffed hours against actual demand | of which Saturday (promotion) | Overstaffed hours |", "|---|---|---|---|---|"]
    published = None
    for name, dem in plans.items():
        o = solver.optimize(ws, dem, time_limit=20)
        m = rules.metrics(ws, o["shifts"], actual)
        sat = sum(v for (d, _, _), v in m["short"].items() if d == 5) / 2
        out.append(f"| {name} | ${m['labor_cost']:,.0f} | {m['understaffed_hours']:.1f} | {sat:.1f} | {m['overstaffed_hours']:.1f} |")
        published = published or (o["shifts"], dem)
    out.append("")

    shifts, dem = published
    rng = random.Random(1)
    sat = [s for s in shifts if s["day"] == 5 and 24 in rules.covers(s)]
    base_short = sum(v for (d, _, _), v in rules.metrics(ws, shifts, dem)["short"].items() if d == 5) / 2
    res = {"min": [], "free": []}
    for _ in range(25):
        gone = rng.sample(sat, 2)
        left = [s for s in shifts if s not in gone]
        opened = sum(v for (d, _, _), v in rules.metrics(ws, left, dem)["short"].items() if d == 5) / 2 - base_short
        for key, weight in (("min", solver.W_CHANGE), ("free", 0)):
            r = solver.repair(ws, dem, left, 5, {s["worker"] for s in gone}, time_limit=5, change_weight=weight)
            m = rules.metrics(ws, r["shifts"], dem)
            after = sum(v for (d, _, _), v in m["short"].items() if d == 5) / 2 - base_short
            res[key].append({"changes": len(r["changes"]), "restored": 1 - max(0.0, after) / max(opened, 0.5), "ms": r["runtime_ms"], "viol": len(m["hard_violations"]), "opened": opened})
    med = lambda k, f: statistics.median(x[f] for x in res[k])      # noqa: E731
    out += ["## 4. Call-out repair (demo store, Saturday)", "", f"25 trials: two people working the 18:00 peak call out (median {med('min', 'opened'):.1f} staff-hours of gap opened). About {len([s for s in shifts if s['day'] == 5])} people work that day.", "",
            "| Repair | Median assignments changed | Most changed | Gap closed (mean) | Rule violations | Median solve time |", "|---|---|---|---|---|---|",
            f"| Minimal-disruption repair (other days frozen, each change penalized) | {med('min', 'changes'):.0f} | {max(x['changes'] for x in res['min'])} | {np.mean([x['restored'] for x in res['min']]):.0%} | {sum(x['viol'] for x in res['min'])} | {med('min', 'ms'):.0f} ms |",
            f"| Baseline: re-solve the day with no penalty for change | {med('free', 'changes'):.0f} | {max(x['changes'] for x in res['free'])} | {np.mean([x['restored'] for x in res['free']]):.0%} | {sum(x['viol'] for x in res['free'])} | {med('free', 'ms'):.0f} ms |", ""]
    (db.ROOT / "docs" / "evaluation.md").write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
